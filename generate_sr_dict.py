"""Generate sr/codes.txt from pydicom's SR concept dictionaries.

pydicom 3.0 keeps the coded terminology in three generated modules:

    sr/_concepts_dict.py   scheme -> keyword -> {code: (meaning, [cids])}
    sr/_cid_dict.py        cid -> {scheme: [keyword]}, plus cid -> name
    sr/_snomed_dict.py     SCT <-> SRT equivalent codes

They are 88k lines of Python literals that the sr package reads as dicts at
import. The same data flattened into one line per fact is smaller, diffable
with a text tool, and can be read once on first use instead of being built
into map literals that every program pays for at start-up.

Record types, tab separated, '#' starts a comment line:

    S  scheme   keyword  code    cids     meaning
    C  cid      name
    I  cid      scheme   keyword
    M  srt_code sct_code

``cids`` is the comma separated list of CIDs the code belongs to, empty when
it belongs to none. No field contains a tab, a newline or a carriage return;
generate() refuses to write a file if one does.

Usage:
    python generate_sr_dict.py [--pydicom PATH] [--check]

--check re-reads the file it would have written and compares it against the
dictionaries, which catches a generator change that loses or reorders data.
"""

import argparse
import importlib.util
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEFAULT_PYDICOM = HERE / "pydicom" / "src" / "pydicom"
OUTPUT = HERE / "sr" / "codes.txt"

HEADER = """\
# The codes of PS3.16, and the contexts (CIDs) that group them.
#
# Generated by generate_sr_dict.py from pydicom {version}'s
# sr/_concepts_dict.py, sr/_cid_dict.py and sr/_snomed_dict.py, which were
# extracted from the DICOM standard, edition {edition}. DO NOT EDIT.
#
# {schemes} schemes, {keywords} keywords, {codes} codes, {cids} CIDs,
# {memberships} CID memberships, {snomed} SCT/SRT equivalences.
#
# Record types, tab separated:
#   S  scheme   keyword  code    cids     meaning
#   C  cid      name
#   I  cid      scheme   keyword
#   M  srt_code sct_code
"""

FORBIDDEN = "\t\n\r"


def load_module(path):
    """Load a module by path, without importing the package it lives in.

    The dictionary modules hold nothing but literals, and importing pydicom
    needs the package, its dependencies and its installed metadata.
    """
    spec = importlib.util.spec_from_file_location(path.stem, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def pydicom_version(pydicom):
    """Return the checkout's version and the standard edition its codes come from.

    _version.py asks the installed metadata for the version, which a checkout
    does not have, so the version comes from pyproject.toml. The edition the
    concept dictionaries were extracted from is a literal in _version.py.
    """
    version = "unknown"
    pyproject = pydicom.parent.parent / "pyproject.toml"
    if pyproject.exists():
        for line in pyproject.read_text(encoding="utf-8").splitlines():
            if line.startswith("version"):
                version = line.split("=", 1)[1].strip().strip("\"'")
                break

    edition = "unknown"
    version_file = pydicom / "_version.py"
    if version_file.exists():
        for line in version_file.read_text(encoding="utf-8").splitlines():
            if line.startswith("__concepts_version__"):
                edition = line.split(":", 1)[1].split("=", 1)[1].strip().strip("\"'")

    return version, edition


def check_field(*values):
    """Refuse a value the line format cannot carry."""
    for value in values:
        if any(ch in value for ch in FORBIDDEN):
            raise SystemExit(f"field contains a tab or newline: {value!r}")


def generate(concepts, cid_concepts, name_for_cid, mapping, version, edition):
    """Return the file contents as a list of lines."""
    schemes = list(concepts)
    keywords = sum(len(v) for v in concepts.values())
    codes = sum(len(e) for v in concepts.values() for e in v.values())
    memberships = sum(len(kws) for v in cid_concepts.values() for kws in v.values())
    snomed = mapping["SRT"]

    out = [
        HEADER.format(
            version=version,
            edition=edition,
            schemes=len(schemes),
            keywords=keywords,
            codes=codes,
            cids=len(name_for_cid),
            memberships=memberships,
            snomed=len(snomed),
        )
    ]

    # Concepts keep the order pydicom declares the schemes in, because
    # Concepts.Collections() hands that order back.
    for scheme in schemes:
        for keyword, entries in concepts[scheme].items():
            for code, (meaning, cids) in entries.items():
                check_field(scheme, keyword, code, meaning)
                out.append(
                    "S\t%s\t%s\t%s\t%s\t%s"
                    % (scheme, keyword, code, ",".join(str(c) for c in cids), meaning)
                )

    # A CID with no keywords is still a CID: twelve of them are named but
    # empty, and pydicom knows they exist. The C line says so.
    for cid in sorted(set(name_for_cid) | set(cid_concepts)):
        name = name_for_cid.get(cid, "")
        check_field(name)
        out.append("C\t%d\t%s" % (cid, name))

    for cid in sorted(cid_concepts):
        for scheme, kws in cid_concepts[cid].items():
            for keyword in kws:
                check_field(scheme, keyword)
                out.append("I\t%d\t%s\t%s" % (cid, scheme, keyword))

    for srt in sorted(snomed):
        out.append("M\t%s\t%s" % (srt, snomed[srt]))

    return out


def parse(lines):
    """Read the generated lines back into the four structures."""
    concepts, cid_concepts, name_for_cid, snomed = {}, {}, {}, {}
    for line in lines:
        if line.startswith("#") or not line:
            continue
        fields = line.split("\t")
        kind = fields[0]
        if kind == "S":
            _, scheme, keyword, code, cids, meaning = fields
            concepts.setdefault(scheme, {}).setdefault(keyword, {})[code] = (
                meaning,
                [int(c) for c in cids.split(",") if c],
            )
        elif kind == "C":
            _, cid, name = fields
            name_for_cid[int(cid)] = name
            cid_concepts.setdefault(int(cid), {})
        elif kind == "I":
            _, cid, scheme, keyword = fields
            cid_concepts.setdefault(int(cid), {}).setdefault(scheme, []).append(keyword)
        elif kind == "M":
            _, srt, sct = fields
            snomed[srt] = sct
        else:
            raise SystemExit(f"unknown record type {kind!r} in {line!r}")
    return concepts, cid_concepts, name_for_cid, snomed


def diff(label, got, want):
    """Return a description of the first difference, or '' when equal."""
    if got == want:
        return ""
    if isinstance(want, dict):
        if set(got) != set(want):
            only_got = sorted(set(got) - set(want))[:3]
            only_want = sorted(set(want) - set(got))[:3]
            return f"{label}: keys differ (extra {only_got}, missing {only_want})"
        for key in want:
            message = diff(f"{label}[{key!r}]", got[key], want[key])
            if message:
                return message
        return f"{label}: equal keys, unequal values"
    return f"{label}: {got!r} != {want!r}"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pydicom", type=Path, default=DEFAULT_PYDICOM)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()

    sr = args.pydicom / "sr"
    concepts = load_module(sr / "_concepts_dict.py").concepts
    cid_dict = load_module(sr / "_cid_dict.py")
    mapping = load_module(sr / "_snomed_dict.py").mapping
    version, edition = pydicom_version(args.pydicom)

    lines = generate(
        concepts,
        cid_dict.cid_concepts,
        cid_dict.name_for_cid,
        mapping,
        version,
        edition,
    )
    body = "\n".join(lines) + "\n"

    if args.check:
        got_concepts, got_cids, got_names, got_snomed = parse(lines)
        problems = [
            diff("concepts", got_concepts, concepts),
            diff("cid_concepts", got_cids, cid_dict.cid_concepts),
            diff("name_for_cid", got_names, cid_dict.name_for_cid),
            diff("snomed", got_snomed, mapping["SRT"]),
        ]
        problems = [p for p in problems if p]
        if problems:
            for problem in problems:
                print(problem, file=sys.stderr)
            return 1
        print(f"round trip ok: {len(lines) - 1} data lines, {len(body)} bytes")
        return 0

    if "\r" in body:
        raise SystemExit("the file would contain a carriage return")

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    # newline="\n" because the default translation on Windows writes CRLF, and
    # a data file that changes with the platform is not one to check in.
    OUTPUT.write_text(body, encoding="utf-8", newline="\n")
    print(f"wrote {OUTPUT} ({len(body)} bytes, {len(lines) - 1} data lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
